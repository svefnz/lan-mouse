//! Concealed clipboard content.
//!
//! Password managers and similar applications mark the clipboard as
//! concealed so that clipboard monitors do not record or forward it.
//! Those markers are respected before a snapshot is stored, so the
//! content never reaches memory, the network, or the peer's clipboard.

use crate::Representation;

/// Representation names whose mere presence marks the content as
/// concealed.
const CONCEALED_NAMES: &[&str] = &[
    // nspasteboard.org conventions
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    // KDE
    "x-kde-passwordManagerHint",
    // Windows
    "ExcludeClipboardContentFromMonitorProcessing",
];

/// Representation names that mark the content as concealed when their
/// value is a zero `u32`.
const CONCEALED_IF_ZERO: &[&str] = &[
    // Windows 10+: 0 means "do not put this in clipboard history / cloud"
    "CanIncludeInClipboardHistory",
    "CanUploadToCloudClipboard",
];

/// Whether the given representations were marked as not for sharing.
pub fn is_concealed(items: &[Representation]) -> bool {
    if items
        .iter()
        .any(|i| CONCEALED_NAMES.contains(&i.name.as_str()))
    {
        return true;
    }
    items.iter().any(|i| {
        CONCEALED_IF_ZERO.contains(&i.name.as_str())
            && i.bytes.len() == 4
            && i.bytes.iter().all(|b| *b == 0)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rep(name: &str, bytes: &[u8]) -> Representation {
        Representation::new(name, bytes.to_vec())
    }

    #[test]
    fn plain_content_is_not_concealed() {
        let items = vec![
            rep("public.utf8-plain-text", b"hello"),
            rep("public.html", b"<b>hello</b>"),
        ];
        assert!(!is_concealed(&items));
    }

    #[test]
    fn concealed_marker_hides_the_whole_snapshot() {
        let items = vec![
            rep("public.utf8-plain-text", b"hunter2"),
            rep("org.nspasteboard.ConcealedType", b""),
        ];
        assert!(is_concealed(&items));
    }

    #[test]
    fn kde_password_hint_is_concealed() {
        let items = vec![
            rep("text/plain", b"hunter2"),
            rep("x-kde-passwordManagerHint", b"secret"),
        ];
        assert!(is_concealed(&items));
    }

    #[test]
    fn windows_exclusion_format_is_concealed() {
        let items = vec![rep("ExcludeClipboardContentFromMonitorProcessing", b"")];
        assert!(is_concealed(&items));
    }

    #[test]
    fn windows_history_flag_is_concealed_only_when_zero() {
        let excluded = vec![rep("CanIncludeInClipboardHistory", &[0, 0, 0, 0])];
        assert!(is_concealed(&excluded));

        let allowed = vec![rep("CanIncludeInClipboardHistory", &[1, 0, 0, 0])];
        assert!(!is_concealed(&allowed));
    }
}
